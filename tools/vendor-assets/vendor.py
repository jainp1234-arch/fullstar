"""Download and convert the vendored UI assets listed in libs/ui/assets/manifest.json.

Runs in python:3.12.15-slim (see `make vendor-assets`) with the pins in requirements.txt.
Sources are fetched at the commits recorded in the manifest. Fonts become WOFF2, Fluent Emoji
PNGs become 256 x 256 WebP (Guidelines §4, §9). Stops on the first missing source file.
"""

import hashlib
import io
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "libs" / "ui" / "assets"
MANIFEST = ASSETS / "manifest.json"


def fetch(repo: str, commit: str, path: str) -> bytes:
    url = f"https://raw.githubusercontent.com/{repo}/{commit}/{urllib.parse.quote(path)}"
    request = urllib.request.Request(url, headers={"User-Agent": "fullstar-vendor-assets"})
    for attempt in range(1, 7):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            raise SystemExit(f"Missing source asset ({error.code}): {repo}@{commit[:7]} {path}") from error
        except (urllib.error.URLError, TimeoutError, ConnectionError) as error:
            if attempt == 6:
                raise SystemExit(f"Could not download {path}: {error}") from error
            time.sleep(2 * attempt)
    raise AssertionError("unreachable")


def to_woff2(data: bytes) -> bytes:
    font = TTFont(io.BytesIO(data))
    font.flavor = "woff2"
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def to_webp_256(data: bytes) -> bytes:
    image = Image.open(io.BytesIO(data)).convert("RGBA")
    image = image.resize((256, 256), Image.Resampling.LANCZOS)
    out = io.BytesIO()
    image.save(out, format="WEBP", quality=90, method=6)
    return out.getvalue()


def symbols_subset(font_data: bytes, codepoints_text: str, names: list[str]) -> tuple[bytes, dict[str, str]]:
    """Material Symbols with fixed axes (wght 500, GRAD 0, opsz 24; FILL kept) and only the listed icons."""
    available = dict(line.split(" ", 1) for line in codepoints_text.strip().splitlines())
    missing = [name for name in names if name not in available]
    if missing:
        raise SystemExit(f"Icons not in Material Symbols Rounded: {', '.join(missing)}")
    chosen = {name: available[name].strip() for name in names}
    font = TTFont(io.BytesIO(font_data))
    # Subset first (instancing the full font trips fontTools), then fix the axes on the small font
    options = subset.Options()
    options.layout_features = []  # no ligatures: components use codepoints
    options.notdef_outline = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=[int(code, 16) for code in chosen.values()])
    subsetter.subset(font)
    font = instancer.instantiateVariableFont(font, {"wght": 500, "GRAD": 0, "opsz": 24})
    out = io.BytesIO()
    font.flavor = "woff2"
    font.save(out)
    return out.getvalue(), chosen


def write_icon_codepoints(chosen: dict[str, str]) -> None:
    lines = [
        "// Generated by tools/vendor-assets/vendor.py from libs/ui/assets/manifest.json. Do not edit.",
        "// Material Symbols Rounded codepoints for the icons in the subset font (Guidelines §8).",
        "export const ICON_CODEPOINTS = {",
    ]
    lines += [f"  {name}: 0x{code}," for name, code in sorted(chosen.items())]
    lines += ["} as const;", "", "export type IconName = keyof typeof ICON_CODEPOINTS;", ""]
    target = ROOT / "libs" / "ui" / "icons" / "icon-codepoints.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    sources = manifest["sources"]
    lock = {}
    for item in manifest["files"]:
        source = sources[item["source"]]
        data = fetch(source["repo"], source["commit"], item["path"])
        converter = item.get("convert")
        if converter == "woff2":
            data = to_woff2(data)
        elif converter == "webp256":
            data = to_webp_256(data)
        elif converter == "symbols-subset":
            codepoints = fetch(source["repo"], source["commit"], item["codepoints"]).decode("utf-8")
            data, chosen = symbols_subset(data, codepoints, manifest["icons"]["names"])
            write_icon_codepoints(chosen)
        target = ASSETS / item["out"]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        lock[item["out"]] = hashlib.sha256(data).hexdigest()
        print(f"ok  {item['out']}  ({len(data)} bytes)")
    (ASSETS / "assets.lock.json").write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
