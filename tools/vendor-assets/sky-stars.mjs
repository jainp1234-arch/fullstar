// Generates libs/ui/assets/sky-stars.svg (Guidelines §7, §10, §18): 40 white dots, 1–2 px,
// 60–100% opacity, at positions from a fixed seed, so the sky is the same on every screen.
// 3 of every 10 stars twinkle between 40% and 100% over 3 s, staggered; none with reduced motion.
// Run: node tools/vendor-assets/sky-stars.mjs
import { writeFileSync } from 'node:fs';

const WIDTH = 400;
const HEIGHT = 200;
const COUNT = 40;

// mulberry32: small deterministic PRNG
function random(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const next = random(20261020);
const stars = [];
for (let i = 0; i < COUNT; i++) {
  const x = (next() * WIDTH).toFixed(1);
  const y = (next() * HEIGHT).toFixed(1);
  const r = (0.5 + next() * 0.5).toFixed(2); // 1–2 px diameter
  const opacity = (0.6 + next() * 0.4).toFixed(2);
  const twinkle = i % 10 < 3;
  const delay = twinkle ? ` style="animation-delay:${((i % 10) * 1).toFixed(1)}s"` : '';
  stars.push(
    `  <circle cx="${x}" cy="${y}" r="${r}" fill="#FFFFFF" opacity="${opacity}"${twinkle ? ' class="tw"' : ''}${delay}/>`,
  );
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" preserveAspectRatio="xMidYMid slice" aria-hidden="true">
  <!-- Generated by tools/vendor-assets/sky-stars.mjs. Do not edit. -->
  <style>
    .tw { animation: twinkle 3s ease-in-out infinite alternate; }
    @keyframes twinkle { from { opacity: .4; } to { opacity: 1; } }
    @media (prefers-reduced-motion: reduce) { .tw { animation: none; } }
  </style>
${stars.join('\n')}
</svg>
`;

writeFileSync(new URL('../../libs/ui/assets/sky-stars.svg', import.meta.url), svg);
console.log(
  `sky-stars.svg: ${COUNT} stars, ${stars.filter((s) => s.includes('class="tw"')).length} twinkle`,
);
